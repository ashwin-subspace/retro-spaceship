package com.ashwin.retrospaceship;

import android.content.res.AssetManager;
import android.graphics.Bitmap;
import android.graphics.BitmapFactory;
import android.graphics.Typeface;

import java.io.IOException;
import java.io.InputStream;
import java.util.HashMap;
import java.util.Map;

/**
 * Every bitmap and typeface the game draws, loaded once at startup.
 *
 * <p>The sprites are white/greyscale on disk. Nothing here recolours them:
 * tinting happens at draw time via a multiply colour filter (see {@link Draw}),
 * which is what lets a single art set serve all four themes with no per-theme
 * bitmap copies sitting in memory.
 */
public final class Assets {

    /** Sprite keys, matching the file names staged into assets/gfx. */
    public static final String PLAYER = "player";
    public static final String BOLT = "bolt";
    public static final String BEAM = "beam";
    public static final String ORB = "orb";
    public static final String ORB_SMALL = "orb_small";
    public static final String MOTE = "mote";
    public static final String BURST = "burst";
    public static final String MINE = "mine";
    public static final String FLAME = "flame";
    public static final String PK_HEAL = "pk_heal";
    public static final String PK_BOMB = "pk_bomb";
    public static final String PK_WEAPON = "pk_weapon";
    public static final String BOSS_ARM = "boss_arm";

    private static final String[] SPRITE_NAMES = {
            "player", "player_wing",
            "e_drone", "e_weaver", "e_darter", "e_seeker", "e_splitter",
            "e_minelayer", "e_tank", "e_shielder", "e_turret",
            "boss_sentinel", "boss_hive", "boss_warden", "boss_arm",
            "bolt", "beam", "orb", "orb_small", "mote", "burst", "mine",
            "pk_heal", "pk_bomb", "pk_weapon",
            "rock_a", "rock_b", "rock_c", "rock_d", "flame",
            "planet0", "planet1", "planet2", "planet3",
    };

    private final Map<String, Bitmap> bitmaps = new HashMap<>();
    /**
     * Per-sprite detail layers, generated by {@code tools/stage_assets.py}.
     *
     * <p>The source art draws its panels as two brightness levels only 18% apart,
     * which a single multiply tint flattens into one shape. These masks carve the
     * lit facets and the linework back out so {@link Draw#detailSprite} can give
     * them separate colours. A sprite with no masks is not an error -- projectiles
     * deliberately have none.
     */
    private final Map<String, Bitmap> litMasks = new HashMap<>();
    private final Map<String, Bitmap> lineMasks = new HashMap<>();

    public Typeface title;
    public Typeface hud;
    public Typeface body;

    public Assets(AssetManager am) {
        BitmapFactory.Options options = new BitmapFactory.Options();
        // ARGB_8888 keeps the soft alpha edges of the source art; the sprites are
        // small enough that the memory cost is irrelevant.
        options.inPreferredConfig = Bitmap.Config.ARGB_8888;
        options.inScaled = false;

        for (String name : SPRITE_NAMES) {
            Bitmap bitmap = load(am, "gfx/" + name + ".png", options);
            if (bitmap != null) {
                bitmaps.put(name, bitmap);
            }
            Bitmap lit = load(am, "gfx/" + name + "_lit.png", options);
            if (lit != null) {
                litMasks.put(name, lit);
            }
            Bitmap line = load(am, "gfx/" + name + "_line.png", options);
            if (line != null) {
                lineMasks.put(name, line);
            }
        }

        title = loadFont(am, "font/title.ttf");
        hud = loadFont(am, "font/hud.ttf");
        body = loadFont(am, "font/body.ttf");
    }

    private static Bitmap load(AssetManager am, String path, BitmapFactory.Options options) {
        InputStream stream = null;
        try {
            stream = am.open(path);
            return BitmapFactory.decodeStream(stream, null, options);
        } catch (IOException e) {
            return null;
        } finally {
            close(stream);
        }
    }

    private static Typeface loadFont(AssetManager am, String path) {
        try {
            return Typeface.createFromAsset(am, path);
        } catch (RuntimeException e) {
            // A missing font must never take the game down; the default face is
            // ugly but entirely playable.
            return Typeface.DEFAULT_BOLD;
        }
    }

    private static void close(InputStream stream) {
        if (stream == null) {
            return;
        }
        try {
            stream.close();
        } catch (IOException ignored) {
            // Nothing useful to do; the decode already succeeded or failed.
        }
    }

    public Bitmap get(String name) {
        return bitmaps.get(name);
    }

    /** The lit facets of a sprite, or null if it has no detail layers. */
    public Bitmap lit(String name) {
        return litMasks.get(name);
    }

    /** The rim, panel boundaries and inlay of a sprite, or null. */
    public Bitmap line(String name) {
        return lineMasks.get(name);
    }

    public Bitmap planet(int index) {
        return bitmaps.get("planet" + Math.max(0, Math.min(3, index)));
    }

    private static final String[] ROCKS = {"rock_a", "rock_b", "rock_c", "rock_d"};

    public static String rockName(int index) {
        return ROCKS[Math.abs(index) % ROCKS.length];
    }

    public Bitmap rock(int index) {
        return bitmaps.get(rockName(index));
    }
}
